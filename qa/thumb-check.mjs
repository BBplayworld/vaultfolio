import { execSync } from "node:child_process";
import { createRequire } from "node:module";
import path from "node:path";
const g = execSync("npm root -g",{encoding:"utf8"}).trim();
const { chromium } = createRequire(path.join(g,"noop.js"))("playwright");
const BASE="https://secretasset-git-issue-434-bbplayworlds-projects.vercel.app";
const browser = await chromium.launch({proxy: process.env.HTTPS_PROXY?{server:process.env.HTTPS_PROXY}:undefined});
const ctx = await browser.newContext({viewport:{width:375,height:812}});
await ctx.addInitScript(()=>{localStorage.setItem("secretasset_tutorial_status",JSON.stringify({1:"done",2:"done",3:"done",4:"done",5:"done"}));});
const page = await ctx.newPage();
await page.goto(`${BASE}/?demo=1`); await page.waitForSelector('html[data-demo-ready="1"]',{state:"attached"}); await page.waitForTimeout(2500);
await page.evaluate(()=>{location.hash="#activity/change"}); await page.waitForTimeout(1500);
await page.evaluate(()=>{const t=document.querySelector('[data-testid="change-hero"] [data-slot=thumb]'); window.__t=t;});
await page.getByTestId("change-period-week").click(); await page.waitForTimeout(100);
console.log("same thumb node after period click:", await page.evaluate(()=>document.querySelector('[data-testid="change-hero"] [data-slot=thumb]')===window.__t));
await page.evaluate(()=>{window.__s=document.querySelector('[data-testid="change-scope-all"]').closest('[role=radiogroup]').querySelector('[data-slot=thumb]')});
await page.getByTestId("change-scope-stock").click(); await page.waitForTimeout(100);
console.log("scope same node:", await page.evaluate(()=>document.querySelector('[data-testid="change-scope-all"]').closest('[role=radiogroup]').querySelector('[data-slot=thumb]')===window.__s));
await browser.close();
